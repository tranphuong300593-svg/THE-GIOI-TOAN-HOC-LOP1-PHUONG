/**
 * Retrieves the 5 questions package for any of the 41 lessons
 * Guaranteed to have accurate bilingual promptEn for every question
 */
export function getLessonQuestionsPackage(lessonId: number): LessonQuestionsPackage {
  const pkg = ALL_LESSON_PACKAGES[lessonId] || ALL_LESSON_PACKAGES[1];
  return {
    ...pkg,
    questions: pkg.questions.map((q) => ({
      ...q,
      promptEn: QUESTION_EN_TRANSLATIONS[q.id] || q.promptEn || '',
    })),
  };
}
